proves(
  ["083-auditor-portal FR-008"],
  "083: the export package verifies offline; a changed entry, item, or signer is named",
  async () => {
    const f = await opened();
    await auditRequestAndSample(f);
    const zip = got(await auditExportZip(f.ctx, ID));
    const files = await unzipped(zip);
    for (const p of [
      "index.json",
      "README.txt",
      "portal.html",
      "populations.json",
      "allowed_signers",
      `bundle/lab-evidence-2026-03.zip`,
    ])
      assert(files[p], p);
    assert(files[`repo/fleets/lab/audits/${ID}/engagement.ts.commit`]);
    assert(files[`repo/fleets/lab/audits/${ID}/trail/0003-sample.md.commit`]);
    assertStringIncludes(dec.decode(files["portal.html"]), "Sample #3");
    const good = await verifyPackage(zip);
    assertEquals(good.problems, []);
    assert(good.ok);
    // With the fleet's signers given from elsewhere: the same.
    assert((await verifyPackage(zip, { allowedSigners: f.allowed })).ok);
    // Someone else's signers: nothing is vouched for.
    const theirs = await verifyPackage(zip, { allowedSigners: `mallory ${f.mallory.pub}\n` });
    assert(!theirs.ok && theirs.problems.some((p) => p.includes("not an allowed signer")));
    const repack = async (
      fn: (x: Record<string, Uint8Array>) => void | Promise<void>,
    ): Promise<Uint8Array> => {
      const x = await unzipped(zip);
      await fn(x);
      return zipped(x);
    };
    // A changed request, even with index.json made to match, is caught by its commit.
    const req = `repo/fleets/lab/audits/${ID}/trail/0001-request.md`;
    const changed = await verifyPackage(
      await repack((x) => {
        x[req] = enc.encode(dec.decode(x[req]).replace("three", "two"));
        const index = JSON.parse(dec.decode(x["index.json"])) as { files: Record<string, string> };
        index.files[req] = "0".repeat(64);
        x["index.json"] = enc.encode(JSON.stringify(index));
      }),
    );
    assert(
      changed.problems.some((p) => p.includes("0001-request.md: changed after its commit")),
      changed.problems.join("; "),
    );
    // A changed evidence item inside the bundle.
    const bundle = "bundle/lab-evidence-2026-03.zip";
    const forged = await verifyPackage(
      await repack(async (x) => {
        const b = await unzipped(got(x[bundle]));
        const obj = got(Object.keys(b).find((k) => k.startsWith("objects/")));
        b[obj] = enc.encode("forged\n");
        x[bundle] = await zipped(b);
      }),
    );
    assert(!forged.ok);
    assert(
      forged.problems.some((p) => p.includes("is not the bundle the engagement pins")),
      forged.problems.join("; "),
    );
    await fs.remove(f.dir, { recursive: true });
  },
  { skip: !hasSsh && "ssh-keygen is not installed" },
);

