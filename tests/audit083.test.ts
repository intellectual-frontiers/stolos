/** The console with the fixture's engagements, signed in with an audit link (or as the operator). */
async function auditConsole(f: Fixture, now = NOW, as: "auditor" | "operator" = "auditor") {
  const deps: AuditDeps = {
    launch: new AuditLaunch(),
    load: (id) => loadCase(f.ctx, id),
    exportZip: async () => got(await auditExportZip(f.ctx, ID)),
    now: () => now,
  };
  const c = await fakeConsole(PORT, { audit: deps });
  const link =
    as === "auditor" ? `/audit/launch?t=${deps.launch.issue(ID)}` : `/launch?t=${c.launch.issue()}`;
  const r = await c.handler(new Request(B + link, { headers: HOST }));
  assertEquals(r.status, 303);
  if (as === "auditor") assertEquals(r.headers.get("location"), `/audit/${ID}/`);
  const cookie = got(got(r.headers.get("set-cookie")).split(";")[0]);
  const req = (path: string, init: RequestInit = {}) =>
    c.handler(
      new Request(B + path, {
        ...init,
        headers: { ...HOST, cookie, ...((init.headers as Record<string, string>) ?? {}) },
      }),
    );
  return { ...c, deps, cookie, req, link };
}

