/**
 * Spec 069: devices: printers, routers, switches, access points, NAS boxes,
 * cameras, UPSes. They run no script, so Stolos reads them over SNMPv3,
 * read-only and encrypted (authPriv), with a user made on the device for it.
 * Each is declared in `fleets/<fleet>/devices/<name>/device.ts`; what it said
 * is in `observed.ts` (GENERATED; `git log -p` is its history). Its passphrases
 * are in the vault (`devices/<name>/snmp.json`), never in Git.
 *
 * @module
 */

import { tsLiteral } from "@intellectual-frontiers/ifc-ts/kernel";
import { fs, path } from "@intellectual-frontiers/ifc-ts/runtime";
import { P } from "../core/paths.ts";
import type { PolicyResult } from "../adopt/policy.ts";
import { defineControl, type ObservationControl } from "../controls/define.ts";
import { runObservations } from "../controls/core.ts";
import { type SnmpCredentials, SnmpSession, type SnmpValue } from "./snmp.ts";

/** What kind of device. */
export const DEVICE_KINDS = [
  "router",
  "switch",
  "access-point",
  "firewall",
  "printer",
  "nas",
  "camera",
  "ups",
  "other",
] as const;

/** A device, as the fleet declares it. */
export type DeviceDef = {
  /** Its name in the fleet (a DNS label). */
  name: string;
  /** What kind of device. */
  kind: (typeof DEVICE_KINDS)[number];
  /** Where Stolos reaches it (an address or a name). */
  address: string;
  /** Its SNMP port (161 unless set). */
  port?: number;
  /** What it is, for people ("Front desk printer"). */
  title?: string;
  /** Who is responsible for it. */
  owner?: string;
  /** Where it is (a room, a rack). */
  location?: string;
  /** The SNMPv3 user Stolos reads it as, and the authentication protocol (privacy is always AES). */
  snmp: { user: string; auth: "sha" | "sha256" };
  /** When it was added (ISO time). */
  added: string;
};

/** What a device said about itself. */
export type DeviceObserved = {
  /** When (ISO time). */
  at: string;
  /** sysDescr: usually the maker, model, and firmware. */
  description: string;
  /** sysName. */
  sysName: string;
  /** sysObjectID: the maker's identifier for the model. */
  objectId: string;
  /** sysContact, as set on the device. */
  contact: string;
  /** sysLocation, as set on the device. */
  location: string;
  /** Days since it last restarted. */
  uptimeDays: number;
  /** How many network interfaces it has. */
  interfaces?: number;
  /** Its serial number (ENTITY-MIB), when it says. */
  serial?: string;
  /** Its firmware or software revision (ENTITY-MIB), when it says. */
  firmware?: string;
  /** Its model name (ENTITY-MIB), when it says. */
  model?: string;
};

/** Where a device's files are. */
export function deviceDir(name: string): string {
  return path.join(P.fleetDir, "devices", name);
}

/** Where its SNMP passphrases are in the vault. */
export function deviceCredPath(name: string): string {
  return path.join(P.secrets, "devices", name, "snmp.json");
}

/** device.ts's text. */
export function deviceSource(d: DeviceDef): string {
  return `// A device (spec 069): Stolos reads it over SNMPv3 (read-only, encrypted); it changes nothing on it.
// Written by \`stolos device add\`; edit title, owner, and location freely.

import type { DeviceDef } from "@intellectual-frontiers/stolos/archon/device/device";

export const device: DeviceDef = ${tsLiteral(d)};
`;
}

/** observed.ts's text. */
export function deviceObservedSource(o: DeviceObserved): string {
  return `// GENERATED by \`stolos device observe\` (spec 069): what the device said over SNMPv3. Never edit by
// hand; \`git log -p\` on this file is the device's history.

import type { DeviceObserved } from "@intellectual-frontiers/stolos/archon/device/device";

export const observed: DeviceObserved = ${tsLiteral(o)};
`;
}

/** What a module exports as `name` (loaded afresh), or undefined. */
async function exported(file: string, name: string): Promise<unknown> {
  const m: unknown = await import(path.toFileUrl(file).href + `?t=${Date.now()}`);
  return typeof m === "object" && m !== null && name in m
    ? (m as Readonly<Record<string, unknown>>)[name]
    : undefined;
}

/** Every device, with its last observation. */
export async function loadDevices(): Promise<
  Array<{ device: DeviceDef; observed?: DeviceObserved }>
> {
  const dir = path.join(P.fleetDir, "devices");
  if (!(await fs.exists(dir))) return [];
  const out: Array<{ device: DeviceDef; observed?: DeviceObserved }> = [];
  const names: string[] = [];
  for await (const e of fs.readDir(dir)) if (e.isDirectory) names.push(e.name);
  for (const n of names.sort()) {
    const f = path.join(dir, n, "device.ts");
    if (!(await fs.exists(f))) continue;
    // device.ts and observed.ts are the files deviceSource and deviceObservedSource write.
    const device = (await exported(f, "device")) as DeviceDef | undefined;
    if (device === undefined) continue;
    const of = path.join(dir, n, "observed.ts");
    const observed = (await fs.exists(of))
      ? ((await exported(of, "observed")) as DeviceObserved | undefined)
      : undefined;
    out.push({ device, ...(observed ? { observed } : {}) });
  }
  return out;
}

const SYS = {
  description: "1.3.6.1.2.1.1.1.0",
  objectId: "1.3.6.1.2.1.1.2.0",
  uptime: "1.3.6.1.2.1.1.3.0",
  contact: "1.3.6.1.2.1.1.4.0",
  sysName: "1.3.6.1.2.1.1.5.0",
  location: "1.3.6.1.2.1.1.6.0",
  interfaces: "1.3.6.1.2.1.2.1.0",
};
const ENTITY = {
  firmware: "1.3.6.1.2.1.47.1.1.1.1.10",
  serial: "1.3.6.1.2.1.47.1.1.1.1.11",
  model: "1.3.6.1.2.1.47.1.1.1.1.13",
};

/** Read a device now. */
export async function observeDevice(
  d: DeviceDef,
  cred: SnmpCredentials,
  now = new Date(),
  session: Pick<SnmpSession, "get" | "walk"> = new SnmpSession(d.address, cred, {
    ...(d.port ? { port: d.port } : {}),
  }),
): Promise<DeviceObserved> {
  const v = await session.get(Object.values(SYS));
  const s = (x: SnmpValue | undefined) => (x === null || x === undefined ? "" : String(x)).trim();
  const firstOf = async (base: string) => {
    try {
      return (await session.walk(base, 20)).map(([, x]) => s(x)).find((x) => x.length > 0);
    } catch {
      return undefined; // ENTITY-MIB is optional: many devices do not have it
    }
  };
  const [serial, firmware, model] = [
    await firstOf(ENTITY.serial),
    await firstOf(ENTITY.firmware),
    await firstOf(ENTITY.model),
  ];
  const ifs = v[SYS.interfaces];
  return {
    at: now.toISOString().replace(/\.\d+Z$/, "Z"),
    description: s(v[SYS.description]),
    sysName: s(v[SYS.sysName]),
    objectId: s(v[SYS.objectId]),
    contact: s(v[SYS.contact]),
    location: s(v[SYS.location]),
    uptimeDays: Math.floor(Number(v[SYS.uptime] ?? 0) / 8_640_000),
    ...(typeof ifs === "number" ? { interfaces: ifs } : {}),
    ...(serial ? { serial } : {}),
    ...(firmware ? { firmware } : {}),
    ...(model ? { model } : {}),
  };
}

/** A device's policies, as controls (spec 078), in the order results are shown. */
export const DEVICE_CONTROLS: ObservationControl<"device">[] = [
  defineControl({
    id: "observed",
    title: "Observed in the last 7 days",
    scf: ["AST-04", "MON-02"],
    subject: "observation",
    of: "device",
    assert: ({ observed: o, now }) => ({
      status: (now - Date.parse(o.at)) / 86_400_000 <= 7 ? "pass" : "fail",
      detail: `last observed ${o.at.slice(0, 10)}`,
    }),
    fix: ({ device: d }) => `bun run stolos device observe ${d.name}`,
  }),
  defineControl({
    id: "snmpv3",
    title: "Read only over encrypted SNMPv3 (authPriv)",
    scf: ["CRY-05"],
    subject: "observation",
    of: "device",
    assert: ({ device: d }) => ({
      status: "pass",
      detail: `user ${d.snmp.user}, ${d.snmp.auth === "sha256" ? "SHA-256" : "SHA-1"} and AES`,
    }),
  }),
  defineControl({
    id: "owner",
    title: "It has an owner and a location",
    scf: ["AST-07.1"],
    subject: "observation",
    of: "device",
    assert: ({ device: d, observed: o }) => ({
      status: (d.owner || o.contact) && (d.location || o.location) ? "pass" : "warn",
      detail: `owner: ${d.owner || o.contact || "none"}; location: ${
        d.location || o.location || "none"
      }`,
    }),
    fix: ({ device: d }) =>
      `set owner and location in fleets/<fleet>/devices/${d.name}/device.ts (or sysContact and sysLocation on the device)`,
  }),
  defineControl({
    id: "restarted",
    title: "Restarted in the last 400 days (firmware updates restart a device)",
    scf: ["VPM-08"],
    subject: "observation",
    of: "device",
    assert: ({ observed: o }) => ({
      status: o.uptimeDays <= 400 ? "pass" : "warn",
      detail: `up ${o.uptimeDays} days${o.firmware ? `; firmware ${o.firmware}` : ""}`,
    }),
    fix: "check the maker's site for firmware updates, and install them",
  }),
];

/** A device's policies. */
export function devicePolicies(
  d: DeviceDef,
  o: DeviceObserved | undefined,
  now = Date.now(),
): PolicyResult[] {
  if (!o) {
    return [
      {
        id: "observed",
        title: "Observed by Stolos",
        scf: ["AST-04"],
        status: "fail",
        detail: "never observed",
        fix: `bun run stolos device observe ${d.name}`,
      },
    ];
  }
  return runObservations(DEVICE_CONTROLS, { device: d, observed: o, now });
}
