/**
 * 036-cli-comforts: `archon shell emit [bash|zsh|fish]` prints the shell code
 * for Archon's aliases, key bindings, prompt, and titles. One line in a
 * shell's startup file turns it all on; without that line a shell gets none
 * of it (Ubuntu's defaults only).
 *
 *   bash  ~/.bashrc                  eval "$(archon shell emit bash)"
 *   zsh   ~/.zshrc                   eval "$(archon shell emit zsh)"
 *   fish  ~/.config/fish/config.fish archon shell emit fish | source
 *
 * The output is code (Article 4), generated here from one table. `archon apply`
 * renders it into /usr/local/share/archon/shell/init.<shell>, and the archon
 * launcher prints that file without starting the engine, so a new shell pays about
 * the cost of `cat`. Everything is guarded: it does nothing in a
 * non-interactive shell, and each piece only when its tool is installed.
 *
 * The prompt: plain (no icons) on a console terminal (the physical console,
 * a serial line, or AMT's), where no Nerd Font exists; Oh My Posh everywhere
 * else. ARCHON_PROMPT=plain or ARCHON_PROMPT=pretty overrides that.
 *
 * @module
 */

import { fs, proc, stdio } from "@intellectual-frontiers/commons/ts/runtime";

/** The shells Archon emits code for. */
export const SHELLS = ["bash", "zsh", "fish"] as const;
/** One of SHELLS. */
export type Shell = (typeof SHELLS)[number];

/** Where `archon apply` renders each shell's init file (`init.<shell>`) and the prompt theme. */
export const SHELL_DIR = "/usr/local/share/archon/shell";
/** The Oh My Posh theme for the pretty prompt. */
export const THEME = `${SHELL_DIR}/archon.omp.json`;
/** For each shell, its startup file and the one line that turns Archon's shell code on. */
export const LINES: Record<Shell, { file: string; line: string }> = {
  bash: { file: "~/.bashrc", line: 'eval "$(archon shell emit bash)"' },
  zsh: { file: "~/.zshrc", line: 'eval "$(archon shell emit zsh)"' },
  fish: { file: "~/.config/fish/config.fish", line: "archon shell emit fish | source" },
};
/** Every archon command writes these (spec 011): with Nerd Font glyphs, and in words. */
const STATUS = "/var/lib/archon/status/prompt";
const STATUS_PLAIN = "/var/lib/archon/status/prompt-plain";
/** Spec 044: "durable" or "ephemeral" (servers); the prompt marks a durable host. */
const DATA = "/etc/archon/data";

/** A tool under each of its names (Ubuntu's first: batcat, fdfind). */
export const TOOLS: Record<string, string[]> = {
  eza: ["eza"],
  bat: ["batcat", "bat"],
  fd: ["fdfind", "fd"],
};

/** The aliases: name -> [tool, arguments]. */
export const ALIASES: Array<{ name: string; tool: keyof typeof TOOLS; args: string }> = [
  { name: "ls", tool: "eza", args: "--group-directories-first" },
  { name: "ll", tool: "eza", args: "-l --git --group-directories-first" },
  { name: "la", tool: "eza", args: "-la --git --group-directories-first" },
  { name: "tree", tool: "eza", args: "--tree" },
  { name: "bat", tool: "bat", args: "" },
  { name: "cat", tool: "bat", args: "--paging=never" },
  { name: "fd", tool: "fd", args: "" },
];

/** POSIX shells (bash, zsh). */
function posix(shell: "bash" | "zsh"): string {
  const L: string[] = [
    `# archon shell emit ${shell} (spec 036). Generated by archon; do not edit.`,
    `# Turned on by this line in ${LINES[shell].file}: ${LINES[shell].line}`,
    `if [[ $- == *i* ]]; then`,
    `__archon_has() { command -v "$1" >/dev/null 2>&1; }`,
    `__archon_first() { local t; for t in "$@"; do __archon_has "$t" && { printf %s "$t"; return 0; }; done; return 1; }`,
    "",
    "# Plain (no icons) on a console terminal, where no Nerd Font exists; pretty everywhere",
    "# else. ARCHON_PROMPT=plain or pretty overrides. It decides the prompt and eza's icons.",
    `__archon_prompt=\${ARCHON_PROMPT:-}`,
    `if [ -z "$__archon_prompt" ]; then`,
    `  case "$TERM:$(tty 2>/dev/null)" in`,
    `    linux:*|vt*:*|*:/dev/tty[0-9]*|*:/dev/ttyS*|*:/dev/ttyUSB*) __archon_prompt=plain ;;`,
    `    *) __archon_prompt=pretty ;;`,
    `  esac`,
    `fi`,
    `__archon_icons=; [ "$__archon_prompt" = pretty ] && __archon_icons=" --icons=auto"`,
    `ARCHON_DATA=; [ -r ${DATA} ] && read -r ARCHON_DATA < ${DATA}; export ARCHON_DATA`,
    `__archon_durable=; [ "$ARCHON_DATA" = durable ] && __archon_durable=' [durable]'`,
    "",
    "# Modern command-line comforts; the originals stay one keystroke away (\\ls, command cat).",
  ];
  for (const [tool, names] of Object.entries(TOOLS)) {
    L.push(`__archon_${tool}=$(__archon_first ${names.join(" ")})`);
  }
  for (const a of ALIASES) {
    L.push(
      // A plain rename (bat -> batcat) only where the names differ.
      `[ -n "$__archon_${a.tool}" ]${
        a.args ? "" : ` && [ "$__archon_${a.tool}" != ${a.name} ]`
      } && alias ${a.name}="$__archon_${a.tool}${a.tool === "eza" ? "$__archon_icons" : ""}${
        a.args ? ` ${a.args}` : ""
      }"`,
    );
  }
  L.push(
    `__archon_has eza || { alias ls='ls --color=auto'; alias ll='ls -alF'; }`,
    "alias grep='grep --color=auto'",
    `if [ -n "$__archon_fd" ]; then`,
    `  export FZF_DEFAULT_COMMAND="$__archon_fd --type f --hidden --exclude .git"`,
    `  export FZF_CTRL_T_COMMAND="$FZF_DEFAULT_COMMAND"`,
    `  export FZF_ALT_C_COMMAND="$__archon_fd --type d --hidden --exclude .git"`,
    "fi",
    `__archon_has fzf && eval "$(fzf --${shell})"`,
    `__archon_has zoxide && eval "$(zoxide init ${shell})"`,
    "__archon_has delta && export GIT_PAGER=delta",
    `unset ${Object.keys(TOOLS)
      .map((t) => `__archon_${t}`)
      .join(" ")}`,
  );
  if (shell === "bash") {
    L.push(
      `__archon_status() {`,
      `  ARCHON_STATUS=; [ -r ${STATUS} ] && read -r ARCHON_STATUS < ${STATUS}; export ARCHON_STATUS`,
      `  __archon_status_plain=; [ -r ${STATUS_PLAIN} ] && read -r __archon_status_plain < ${STATUS_PLAIN}`,
      `}`,
      `# The terminal title (spec 011): "bash in alice@alpha", as fish and Oh My Posh set it.`,
      `__archon_title() { case "$TERM" in xterm*|tmux*|screen*|alacritty|foot*|wezterm) printf '\\033]0;bash in %s@%s\\007' "$USER" "\${HOSTNAME%%.*}" ;; esac; }`,
      `PROMPT_COMMAND="__archon_status; __archon_title\${PROMPT_COMMAND:+; $PROMPT_COMMAND}"`,
      `if [ "$__archon_prompt" = pretty ] && __archon_has oh-my-posh && [ -r ${THEME} ]; then`,
      `  eval "$(oh-my-posh init bash --config ${THEME})"`,
      `else`,
      `  PS1='\\u@\\h\${__archon_durable}:\\w\${__archon_status_plain:+ [$__archon_status_plain]}\\$ '`,
      `fi`,
    );
  } else {
    L.push(
      `__archon_status() {`,
      `  ARCHON_STATUS=; [ -r ${STATUS} ] && read -r ARCHON_STATUS < ${STATUS}; export ARCHON_STATUS`,
      `  __archon_status_plain=; [ -r ${STATUS_PLAIN} ] && read -r __archon_status_plain < ${STATUS_PLAIN}`,
      `  case "$TERM" in xterm*|tmux*|screen*|alacritty|foot*|wezterm) print -Pn "\\e]0;zsh in %n@%m\\a" ;; esac`,
      `}`,
      `autoload -Uz add-zsh-hook && add-zsh-hook precmd __archon_status`,
      `if [ "$__archon_prompt" = pretty ] && __archon_has oh-my-posh && [ -r ${THEME} ]; then`,
      `  eval "$(oh-my-posh init zsh --config ${THEME})"`,
      `else`,
      `  setopt PROMPT_SUBST`,
      `  PROMPT='%n@%m\${__archon_durable}:%~\${__archon_status_plain:+ [$__archon_status_plain]}%# '`,
      `fi`,
    );
  }
  L.push("unset __archon_prompt __archon_icons; unset -f __archon_first", "fi", "");
  return L.join("\n");
}

function fish(): string {
  const L: string[] = [
    "# archon shell emit fish (spec 036). Generated by archon; do not edit.",
    `# Turned on by this line in ${LINES.fish.file}: ${LINES.fish.line}`,
    "if status is-interactive",
    "    set --global fish_greeting",
    '    # The terminal title (spec 011): "fish in alice@alpha", the same as Oh My Posh\'s.',
    "    function fish_title",
    '        echo "fish in $USER@"(prompt_hostname)',
    "    end",
    "",
    "    # Plain (no icons) on a console terminal; pretty elsewhere (ARCHON_PROMPT overrides): the prompt and eza's icons.",
    "    set --local __archon_prompt $ARCHON_PROMPT",
    '    if test -z "$__archon_prompt"',
    "        set --local __archon_tty (tty 2>/dev/null)",
    "        if string match --quiet --regex '^(linux|vt)' -- \"$TERM\"; or string match --quiet --regex '^/dev/tty(S|USB)?[0-9]' -- \"$__archon_tty\"",
    "            set __archon_prompt plain",
    "        else",
    "            set __archon_prompt pretty",
    "        end",
    "    end",
    "    set --local __archon_icons",
    '    test "$__archon_prompt" = pretty; and set __archon_icons " --icons=auto"',
    "",
    "    # Modern command-line comforts; the originals stay one keystroke away (command ls).",
  ];
  for (const [tool, names] of Object.entries(TOOLS)) {
    L.push(
      `    set --local __archon_${tool} (command --search ${names.join(
        " ",
      )} | head -n 1 | string replace --regex '.*/' '')`,
    );
  }
  for (const a of ALIASES) {
    L.push(
      `    test -n "$__archon_${a.tool}"${
        a.args ? "" : `; and test "$__archon_${a.tool}" != ${a.name}`
      }; and alias ${a.name} "$__archon_${a.tool}${a.tool === "eza" ? "$__archon_icons" : ""}${
        a.args ? ` ${a.args}` : ""
      }"`,
    );
  }
  L.push(
    '    if test -n "$__archon_fd"',
    '        set --global --export FZF_DEFAULT_COMMAND "$__archon_fd --type f --hidden --exclude .git"',
    "        set --global --export FZF_CTRL_T_COMMAND $FZF_DEFAULT_COMMAND",
    '        set --global --export FZF_ALT_C_COMMAND "$__archon_fd --type d --hidden --exclude .git"',
    "    end",
    "    command --query fzf; and fzf --fish | source",
    // zoxide copies fish's cd function from $__fish_data_dir/functions/cd.fish,
    // which fish 4 no longer ships as a file (its functions are built in): give
    // zoxide that copy from the built-in function first, so it skips the file.
    "    if command --query zoxide",
    "        if not functions --query __zoxide_cd_internal; and functions --query cd",
    "            functions cd | string replace --regex -- '^function cd\\b' 'function __zoxide_cd_internal' | source",
    "        end",
    "        zoxide init fish | string replace --regex -- '.*__fish_data_dir/functions/cd\\.fish.*' '' | source",
    "    end",
    "    command --query delta; and set --global --export GIT_PAGER delta",
    "",
    "    # archon's abbreviations, for operators (the archon-ops group).",
    "    if command --query archon; and contains archon-ops (id -nG | string split ' ')",
    "        abbr --add ab 'stolos build'",
    "        abbr --add ac 'archon apply --check'",
    "        abbr --add av 'archon verify'",
    "        abbr --add ad 'archon capture --summary'",
    "    end",
    "",
    "    function __archon_status --on-event fish_prompt",
    '        set --global --export ARCHON_STATUS ""',
    `        test -r ${STATUS}; and read --global --export ARCHON_STATUS < ${STATUS}`,
    '        set --global __archon_status_plain ""',
    `        test -r ${STATUS_PLAIN}; and read --global __archon_status_plain < ${STATUS_PLAIN}`,
    "    end",
    "    __archon_status",
    '    set --global --export ARCHON_DATA ""',
    `    test -r ${DATA}; and read --global --export ARCHON_DATA < ${DATA}`,
    `    if test "$__archon_prompt" = pretty; and command --query oh-my-posh; and test -r ${THEME}`,
    `        oh-my-posh init fish --config ${THEME} | source`,
    "    else",
    "        function fish_prompt",
    '            set --local s ""',
    '            test -n "$__archon_status_plain"; and set s " [$__archon_status_plain]"',
    '            set --local d ""',
    '            test "$ARCHON_DATA" = durable; and set d " [durable]"',
    '            echo -n "$USER@"(prompt_hostname)"$d:"(prompt_pwd)"$s> "',
    "        end",
    "    end",
    "end",
    "",
  );
  return L.join("\n");
}

/** The shell code for `shell`: aliases, key bindings, prompt and titles. */
export function renderEmit(shell: Shell): string {
  return shell === "fish" ? fish() : posix(shell);
}

/** Which shell asked: the explicit name, else the parent process, else $SHELL. */
export async function detectShell(explicit?: string): Promise<Shell | undefined> {
  const pick = (s?: string) => {
    const n = (s ?? "").trim().replace(/^-/, "").split("/").pop() ?? "";
    return (SHELLS as readonly string[]).includes(n) ? (n as Shell) : undefined;
  };
  if (explicit) return pick(explicit);
  try {
    const stat = await fs.readTextFile(`/proc/${proc.ppid()}/comm`);
    const p = pick(stat);
    if (p) return p;
  } catch {
    /* no /proc */
  }
  return pick(proc.env.get("SHELL"));
}

/** `archon shell emit`: print the code (the launcher prints the rendered file directly). */
export async function shellEmit(name?: string): Promise<number> {
  const shell = await detectShell(name);
  if (!shell) {
    stdio.stderr.writeSync(
      `${
        `archon shell emit: name the shell (bash, zsh, or fish)${name ? `, not ${name}` : ""}.\n` +
        Object.values(LINES)
          .map((l) => `  ${l.file}: ${l.line}`)
          .join("\n")
      }\n`,
    );
    return 2;
  }
  await stdio.stdout.write(renderEmit(shell));
  return 0;
}

/** `archon shell status`: which startup files carry the line. */
export async function shellStatus(): Promise<number> {
  const home = proc.env.get("HOME") ?? "";
  const out: string[] = [];
  let any = false;
  for (const s of SHELLS) {
    const path = LINES[s].file.replace(/^~/, home);
    const text = await fs.readTextFile(path).catch(() => undefined);
    const on = !!text && /archon shell emit/.test(text);
    any ||= on;
    out.push(
      `  ${on ? "✓" : "·"} ${s.padEnd(5)} ${LINES[s].file}${
        on ? "" : text === undefined ? "  (no such file)" : `  add: ${LINES[s].line}`
      }`,
    );
  }
  stdio.stdout.writeSync(
    `${[
      "Archon's shell features (aliases, fzf keys, zoxide, the prompt, titles) are on where",
      "a startup file runs archon shell emit:",
      ...out,
      any ? "" : "None of your startup files has the line: add it to the one for your shell.",
    ].join("\n")}\n`,
  );
  return 0;
}
