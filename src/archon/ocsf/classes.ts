/**
 * Spec 089: the OCSF 1.9.0 classes Stolos emits, and the names of the OCSF objects, the vocabulary
 * Stolos names its tables and labels from (`schema/vocabulary.ts`).
 *
 * The OCSF types themselves are IFC TypeScript's (kernel `ocsf`, generated there from the pinned
 * OCSF 1.9.0 schema). The kernel types classes 2003, 2002, 5001, 5003 and 5023; the connectors also
 * record nodes as 5020 Software Inventory Info, 5004 Operating System Patch State, 5040 Live Evidence
 * Info and 2008 IAM Analysis Finding, which the kernel does not type yet, so this table names them
 * by their uid, caption and category alone (a commons gap). The object names are those of every
 * object the emitted classes use, as OCSF 1.9.0 names them.
 *
 * @module
 */
// Spec: 089-ocsf-schema-language

import { ocsf } from "@intellectual-frontiers/commons/ts/kernel";

/** The OCSF version Stolos writes. */
export const OCSF_VERSION: typeof ocsf.OCSF_VERSION = ocsf.OCSF_VERSION;

/** The classes Stolos emits: their uid, caption, and category, by OCSF's class name. */
export const OCSF_CLASSES = {
  inventory_info: { uid: 5001, caption: "Device Inventory Info", category_uid: 5 },
  user_inventory: { uid: 5003, caption: "User Inventory Info", category_uid: 5 },
  software_info: { uid: 5020, caption: "Software Inventory Info", category_uid: 5 },
  patch_state: { uid: 5004, caption: "Operating System Patch State", category_uid: 5 },
  cloud_resources_inventory_info: {
    uid: 5023,
    caption: "Cloud Resources Inventory Info",
    category_uid: 5,
  },
  evidence_info: { uid: 5040, caption: "Live Evidence Info", category_uid: 5 },
  compliance_finding: { uid: 2003, caption: "Compliance Finding", category_uid: 2 },
  vulnerability_finding: { uid: 2002, caption: "Vulnerability Finding", category_uid: 2 },
  iam_analysis_finding: { uid: 2008, caption: "IAM Analysis Finding", category_uid: 2 },
} as const;

/** An OCSF class Stolos emits, by its name (`compliance_finding`). */
export type OcsfClassName = keyof typeof OCSF_CLASSES;

/** The OCSF class name of a class uid (`compliance_finding` for 2003), or `class_<uid>`. */
export function ocsfClassName(uid: number): string {
  return Object.entries(OCSF_CLASSES).find(([, c]) => c.uid === uid)?.[0] ?? `class_${uid}`;
}

