/**
 * Spec 072: `stolos evidence export --from <date> --to <date>` gathers a
 * period's evidence from the fleet repository and this PC, and signs it with
 * your daily key (ssh-keygen asks its passphrase in this terminal; Stolos
 * never sees it). `stolos evidence verify <bundle>` checks one, offline.
 *
 * @module
 */

import { ui } from "../core/ui.ts";
import { run } from "../core/exec.ts";
import { join } from "../core/path.ts";
import { P, repoRel } from "../core/paths.ts";
import {
  type Item,
  manifestFor,
  manifestText,
  packBundle,
  type Signer,
  sshSigner,
  verifyBundle,
} from "./bundle.ts";

const enc = new TextEncoder();
const DATE = /^\d{4}-\d{2}-\d{2}$/;

/** A fleet path that holds an observation (GENERATED by Stolos from what it saw). */
export function isObservation(path: string): boolean {
  return /\/(observed|discovered)\.ts$/.test(path) ||
    (/\/estate\/[^/]+\.ts$/.test(path) && !path.endsWith("/links.ts"));
}

async function git(repo: string, args: string[]): Promise<string> {
  const r = await run(["git", "-C", repo, ...args]);
  if (!r.ok) throw new Error(`git ${args.join(" ")}: ${r.stderr.trim()}`);
  return r.stdout;
}

/** The period's evidence from Git: each commit (raw, with its signature) and each observation it recorded. */
export async function gitItems(
  repo: string,
  fleetPath: string,
  from: string,
  to: string,
): Promise<Item[]> {
  const until = new Date(Date.parse(`${to}T00:00:00Z`) + 86_400_000).toISOString();
  const log = await git(repo, [
    "log",
    "--reverse",
    `--since=${from}T00:00:00Z`,
    `--until=${until}`,
    "--format=%H %cI",
  ]);
  const items: Item[] = [];
  for (const line of log.split("\n").filter(Boolean)) {
    const [sha, at] = line.split(" ");
    const raw = await run(["git", "-C", repo, "cat-file", "commit", sha]);
    items.push({ kind: "commit", name: `commit ${sha}`, at, content: enc.encode(raw.stdout) });
    const changed = await git(repo, [
      "diff-tree",
      "--no-commit-id",
      "--name-status",
      "-r",
      "--root",
      sha,
      "--",
      fleetPath,
    ]);
    for (const c of changed.split("\n").filter(Boolean)) {
      const [status, path] = c.split("\t");
      if (status === "D" || !isObservation(path)) continue;
      const body = await run(["git", "-C", repo, "show", `${sha}:${path}`]);
      items.push({
        kind: "observation",
        name: `${path} @ ${sha.slice(0, 12)}`,
        at,
        content: enc.encode(body.stdout),
      });
    }
  }
  return items;
}

/** The period's verify and install results this PC recorded. */
export async function verifyItems(from: string, to: string, dir = P.state): Promise<Item[]> {
  const { allRecords } = await import("../state/store.ts");
  const end = `${to}T23:59:59.999Z`;
  return (await allRecords(dir).catch(() => []))
    .filter((r) => (r.kind === "verify" || r.kind === "install") && r.at >= from && r.at <= end)
    .sort((a, b) => a.at.localeCompare(b.at))
    .map((r) => ({
      kind: "verify" as const,
      name: `${r.host} ${r.kind} ${r.name}`,
      at: r.at,
      content: enc.encode(JSON.stringify(r, null, 2) + "\n"),
    }));
}

/** Make a bundle for the period; returns where it was written. */
export async function evidenceExport(
  from: string,
  to: string,
  o: { out?: string; key?: string; signer?: Signer; now?: Date } = {},
): Promise<number> {
  const p = ui.phase("Evidence");
  if (!DATE.test(from) || !DATE.test(to) || from > to) {
    p.fail(
      "--from and --to are dates (YYYY-MM-DD), from before to",
      "for example --from 2026-01-01 --to 2026-06-30",
    );
    return 1;
  }
  const { loadFleet } = await import("../model/load.ts");
  const { loadSigners, signersFile } = await import("../identity/signers.ts");
  const { keyPaths, pubOf } = await import("../identity/keys.ts");
  const { VERSION } = await import("../version.ts");
  const fleet = await loadFleet();
  const signers = await loadSigners();
  const repo = P.repo;
  const now = o.now ?? new Date();
  const key = o.key ??
    keyPaths((await run(["git", "-C", repo, "config", "user.signingkey"])).stdout.trim()).daily;
  const pub = pubOf(await Deno.readTextFile(key + ".pub").catch(() => undefined));
  const me = signers.find((s) => pub && s.key.trim().split(/\s+/).slice(0, 2).join(" ") === pub);
  if (!me) {
    p.fail(
      `${key} is not one of the fleet's signers`,
      "deno task stolos keys (set up your daily key)",
    );
    return 1;
  }
  const items: Item[] = [];
  const omitted: string[] = [];
  items.push(...await gitItems(repo, repoRel(P.fleetDir), from, to));
  items.push(...await verifyItems(from, to));
  if (!items.some((i) => i.kind === "verify")) {
    omitted.push("verify: no results recorded on this PC in the period");
  }
  const sig = await Deno.readTextFile(signersFile());
  items.push({
    kind: "signers",
    name: repoRel(signersFile()),
    at: now.toISOString(),
    content: enc.encode(sig),
  });
  const { loadScf, loadNist } = await import("../compliance/catalog.ts");
  const catalog = await loadScf();
  if (catalog) {
    const { pcFacts } = await import("../console/pc.ts");
    const { complianceView, fleetEvidence } = await import("../compliance/report.ts");
    const { assessmentResults } = await import("../compliance/oscal.ts");
    const f = await pcFacts();
    const nist = await loadNist("nist80053");
    const ar = await assessmentResults({
      view: complianceView(fleetEvidence(f), catalog),
      fleet: f.fleet,
      machines: f.machines,
      ...(nist ? { titles: nist.titles } : {}),
      version: VERSION,
      now,
    });
    const { tidyStrings } = await import("../compliance/oscal.ts");
    items.push({
      kind: "oscal",
      name: "assessment-results.json",
      at: now.toISOString(),
      content: enc.encode(JSON.stringify(tidyStrings(ar), null, 2) + "\n"),
    });
  } else {omitted.push(
      "oscal: the SCF catalog is not on this PC (deno task stolos compliance catalog)",
    );}
  const m = await manifestFor(items, {
    fleet: { id: fleet.id, title: fleet.title || fleet.id, repo: fleet.repository.slug },
    period: { from, to },
    created: now.toISOString().replace(/\.\d+Z$/, "Z"),
    stolos: VERSION,
    signer: me.name,
    omitted,
  });
  p.ok(
    `${items.length} item(s): ${
      ["commit", "observation", "verify", "oscal"].map((k) =>
        `${items.filter((i) => i.kind === k).length} ${k}`
      ).join(", ")
    }`,
  );
  for (const x of omitted) p.warn(x);
  p.note(`signing as ${me.name}: ssh-keygen asks your key's passphrase`);
  let signature: string;
  try {
    signature = await (o.signer ?? sshSigner(key))(manifestText(m));
  } catch (e) {
    p.fail((e as Error).message, "deno task stolos keys");
    return 1;
  }
  const { allowedSignersText } = await import("../identity/signers.ts");
  const allowed = allowedSignersText(signers).replace(
    /namespaces="git"/g,
    'namespaces="git,stolos-evidence"',
  );
  const file = o.out ?? join(P.state, "evidence", `${fleet.id}-evidence-${from}-to-${to}.zip`);
  await Deno.mkdir(join(file, ".."), { recursive: true });
  await Deno.writeFile(file, packBundle(items, m, signature, allowed));
  p.done(file);
  ui.next.push(`check it (anyone, offline): deno task stolos evidence verify ${file}`);
  return 0;
}

/** Check a bundle; exit 1 with each reason when anything is wrong. */
export async function evidenceVerify(
  file: string,
  signersFile?: string,
  json = false,
): Promise<number> {
  const p = ui.phase("Evidence");
  let zip: Uint8Array;
  try {
    zip = await Deno.readFile(file);
  } catch (e) {
    p.fail(`${file}: ${(e as Error).message}`);
    return 1;
  }
  const allowed = signersFile ? await Deno.readTextFile(signersFile) : undefined;
  const r = await verifyBundle(zip, allowed ? { allowedSigners: allowed } : {});
  if (json) {
    console.log(
      JSON.stringify(
        {
          ok: r.ok,
          problems: r.problems,
          signer: r.signer,
          commits: r.commits,
          manifest: r.manifest && { ...r.manifest, items: r.manifest.items.length },
        },
        null,
        2,
      ),
    );
    return r.ok ? 0 : 1;
  }
  const m = r.manifest;
  if (m) {
    p.note(
      `${m.fleet.title} (${m.fleet.id}), ${m.period.from} to ${m.period.to}: ${m.items.length} item(s), made ${m.created}`,
    );
  }
  for (const x of r.problems) p.warn(x);
  if (!r.ok) {
    p.fail(`${r.problems.length} problem(s): do not rely on this bundle`);
    return 1;
  }
  p.done(
    `every item unchanged and chained; signed by ${r.signer}; ${r.commits.length} commit(s) signed by ${
      [...new Set(r.commits.map((c) => c.signer))].join(", ") || "nobody"
    }`,
  );
  if (!signersFile) {
    ui.next.push(
      "the bundle's own signers vouched for it: pass --signers with the fleet's allowed_signers you have from elsewhere",
    );
  }
  return 0;
}
