/**
 * Spec 067 (clouds): what the fleet has in its cloud accounts, for people and
 * auditors. Stolos reads each account with a read-only credential kept in the
 * vault, writes what it found to `fleets/<fleet>/clouds/<provider>.ts`
 * (GENERATED, so `git log -p` is the account's history), and checks a few
 * posture policies. It never changes a cloud: managing clouds is out of scope.
 *
 * Providers, in the fleet's order: Cloudflare (the primary cloud), Microsoft
 * 365 and Azure, AWS, Hetzner.
 *
 * @module
 */

import { join } from "../core/path.ts";
import { P } from "../core/paths.ts";
import { tsLiteral } from "../core/ts-literal.ts";
import type { PolicyResult } from "../adopt/policy.ts";

/** One thing in a cloud account: a zone, a DNS record, a server, a bucket, a user, ... */
export interface CloudAsset {
  /** What it is: zone, dns-record, worker, r2-bucket, server, s3-bucket, user, ... */
  kind: string;
  /** The provider's id for it. */
  id: string;
  /** Its name for people. */
  name: string;
  /** Where it is (region, location, zone), when that means something. */
  where?: string;
  /** The managed host or adopted machine it belongs to, when Stolos can tell. */
  fleetMachine?: string;
  /** The few facts worth seeing (no secrets: providers never return them to a read-only token). */
  facts?: Record<string, string | number | boolean>;
}

/** What one cloud account holds, as observed. */
export interface CloudObserved {
  /** When (ISO time). */
  at: string;
  /** The provider: cloudflare, microsoft, aws, hetzner. */
  provider: string;
  /** The account (or tenant, or project) for people. */
  account: string;
  /** Everything found. */
  assets: CloudAsset[];
  /** Posture facts the policies read (per provider). */
  posture: Record<string, string | number | boolean>;
  /** What could not be read, and why (a missing permission, usually). */
  gaps: string[];
}

/** An HTTP GET or POST that returns parsed JSON or text; injectable for tests. */
export type Http = (
  url: string,
  init?: { method?: string; headers?: Record<string, string>; body?: string },
) => Promise<{ status: number; text: string }>;

/** The real one: fetch. */
export const realHttp: Http = async (url, init): Promise<{ status: number; text: string }> => {
  const r = await fetch(url, {
    method: init?.method ?? "GET",
    headers: init?.headers,
    body: init?.body,
    signal: AbortSignal.timeout(30_000),
  });
  return { status: r.status, text: await r.text() };
};

/** A provider: how to connect, what to read, what to check. */
export interface CloudProvider {
  /** Its id (the vault folder and the file name). */
  id: string;
  /** Its name for people. */
  title: string;
  /** The Simple Icons slug for its logo, or "" when its owner does not allow one there. */
  logo: string;
  /** What to create in the provider's console, step by step: read-only access only. */
  connectHelp: string[];
  /** The fields the credential has (one is a token; several make a JSON credential). */
  fields: Array<{ name: string; secret: boolean; hint: string }>;
  /** Read the account. */
  observe(cred: Record<string, string>, http: Http, now: Date): Promise<CloudObserved>;
  /** Its posture policies. */
  policies(o: CloudObserved, now: number): PolicyResult[];
}

/** Where a provider's credential is in the vault. */
export function cloudCredPath(id: string): string {
  return join(P.secrets, "clouds", id, "credential.json");
}

/** Where a provider's observation is in the fleet repository. */
export function cloudFile(id: string): string {
  return join(P.fleetDir, "clouds", `${id}.ts`);
}

/** The observation's TypeScript. */
export function cloudSource(o: CloudObserved): string {
  return `// GENERATED by \`stolos cloud observe\` (spec 067): what ${o.provider} holds, read with a
// read-only credential. Never edit by hand; \`git log -p\` on this file is the account's history.

import type { CloudObserved } from "@stolos/archon/cloud/cloud.ts";

export const observed: CloudObserved = ${tsLiteral(o)};
`;
}

/** A JSON body, or a clear error naming the call. */
export async function getJson<T>(
  http: Http,
  url: string,
  headers: Record<string, string>,
  method = "GET",
  body?: string,
): Promise<T> {
  const r = await http(url, { method, headers, ...(body !== undefined ? { body } : {}) });
  if (r.status === 401 || r.status === 403) {
    throw new CloudDenied(
      `${new URL(url).pathname}: ${r.status} (the credential may not read this)`,
    );
  }
  if (r.status >= 400) throw new Error(`${new URL(url).pathname}: HTTP ${r.status}`);
  try {
    return JSON.parse(r.text) as T;
  } catch {
    throw new Error(`${new URL(url).pathname}: not JSON`);
  }
}

/** A call the credential is not allowed to make: a gap, not a failure. */
export class CloudDenied extends Error {}

/** Run `f`; a denial becomes a gap and `fallback`. */
export async function orGap<T>(
  gaps: string[],
  what: string,
  fallback: T,
  f: () => Promise<T>,
): Promise<T> {
  try {
    return await f();
  } catch (e) {
    if (e instanceof CloudDenied) {
      gaps.push(`${what}: ${e.message}`);
      return fallback;
    }
    throw e;
  }
}

/** One posture policy from a boolean (or unknown when the fact is missing). */
export function check(
  o: CloudObserved,
  p: {
    id: string;
    title: string;
    scf: string[];
    fact: string;
    want: (v: unknown) => boolean;
    fix: string;
    warnOnly?: boolean;
  },
): PolicyResult {
  const v = o.posture[p.fact];
  const status = v === undefined ? "unknown" : p.want(v) ? "pass" : p.warnOnly ? "warn" : "fail";
  return {
    id: p.id,
    title: p.title,
    scf: p.scf,
    status,
    detail: v === undefined ? `${p.fact}: not readable` : `${p.fact}: ${v}`,
    fix: p.fix,
  };
}

/** The observed-recently policy every provider has. */
export function fresh(o: CloudObserved, now: number, id: string): PolicyResult {
  const days = (now - Date.parse(o.at)) / 86_400_000;
  return {
    id: "observed",
    title: "Observed in the last 7 days",
    scf: ["AST-02", "MON-01"],
    status: days <= 7 ? "pass" : "fail",
    detail: `last observed ${o.at.slice(0, 10)}`,
    fix: `deno task stolos cloud observe ${id}`,
  };
}
