/**
 * Spec 047-intent-and-identity (Article 9): who may approve a fleet's changes,
 * and how a host checks an approval before it applies anything.
 *
 * - fleets/<id>/signers.ts lists the signers. It is written by `archon signers`
 *   in one fixed form (a typed literal, Article 4); `archon build` fails when
 *   it is not in that form.
 * - Every host keeps /etc/archon/allowed_signers (Git's format), rendered from
 *   the signers of the last commit it accepted, plus any key a person trusted
 *   on the host itself in an emergency (/etc/archon/allowed_signers.local).
 * - Before a host moves to a new tip of main, the tip must be signed by a key
 *   it already trusts, and must come after the commit it last applied. So the
 *   list of signers changes only through a commit signed by a key already on it.
 *
 * ```mermaid
 * flowchart TD
 *   fetch["git fetch: the new tip of main"] --> desc{"descends from the<br/>commit this host runs?"}
 *   desc -->|no| rb["refused: E047-ROLLBACK"]
 *   desc -->|yes| any{"signers.ts lists<br/>a daily signer?"}
 *   any -->|no| ns["refused: E047-NO-SIGNERS"]
 *   any -->|yes| sig{"signed?"}
 *   sig -->|no| us["refused: E047-UNSIGNED"]
 *   sig -->|yes| trust{"by a key the host trusts<br/>(its allowed_signers)?"}
 *   trust -->|no| ut["refused: E047-UNTRUSTED"]
 *   trust -->|yes| move["fast-forward, apply"]
 * ```
 *
 * @module
 */

import { P } from "../core/paths.ts";
import { join } from "../core/path.ts";
import { exists, readTextOr } from "../core/fsx.ts";
import { run } from "../core/exec.ts";
import { toFileUrl } from "../core/path.ts";
import type { SignerDef } from "../model/types.ts";

export const ALLOWED_SIGNERS = "/etc/archon/allowed_signers";
export const ALLOWED_SIGNERS_LOCAL = "/etc/archon/allowed_signers.local";
const KEY = /^(ssh-ed25519|sk-ssh-ed25519@openssh\.com) [A-Za-z0-9+/]+={0,2}$/;
const NAME = /^[a-z0-9][a-z0-9._-]{0,63}$/;

/** fleets/<id>/signers.ts */
export function signersFile(): string {
  return join(P.fleetDir, "signers.ts");
}

/** The fixed form of signers.ts: what `archon signers` writes, and what build checks. */
export function signersSource(list: SignerDef[]): string {
  const rows = [...list].sort((a, b) => a.name.localeCompare(b.name)).map((s) =>
    `  {\n    name: ${JSON.stringify(s.name)},\n    role: ${JSON.stringify(s.role)},\n    key: ${
      JSON.stringify(s.key)
    },\n    added: ${JSON.stringify(s.added)},\n  },\n`
  ).join("");
  return `// Written by archon signers (spec 047): who may approve this fleet's changes.
// Change it with archon signers add/remove, in a commit signed by a key below.
import type { SignerDef } from "@stolos/archon/model/types.ts";

export default [
${rows}] satisfies SignerDef[];
`;
}

/** The signers in this fleet's signers.ts ([] when there is none yet). */
export async function loadSigners(file = signersFile()): Promise<SignerDef[]> {
  if (!(await exists(file))) return [];
  const mod = await import(toFileUrl(file).href + `?t=${Date.now()}`);
  return (mod.default ?? []) as SignerDef[];
}

/** Problems with a list of signers (validation, Article 10). */
export function signerProblems(list: SignerDef[]): Array<{ message: string; fix: string }> {
  const out: Array<{ message: string; fix: string }> = [];
  if (!list.some((s) => s.role === "daily")) {
    out.push({
      message: "no daily signer: no change can be approved, and hosts apply nothing new",
      fix: "archon signers add <name> --role daily --key <public key or .pub file>",
    });
  }
  const seen = new Set<string>();
  for (const s of list) {
    if (!NAME.test(s.name)) {
      out.push({
        message: `signer name '${s.name}' is not usable`,
        fix: "lowercase, digits, . _ -",
      });
    }
    if (seen.has(s.name)) {
      out.push({ message: `signer ${s.name} is listed twice`, fix: "keep one" });
    }
    seen.add(s.name);
    if (!KEY.test(s.key.trim())) {
      out.push({
        message: `signer ${s.name}: not an ed25519 public key`,
        fix: "use the one line of its .pub file (ssh-ed25519 AAAA...), without a comment",
      });
    }
  }
  return out;
}

/** Git's allowed_signers: one line per signer, for commit signatures only. */
export function allowedSignersText(list: SignerDef[], local = ""): string {
  const lines = [...list].sort((a, b) => a.name.localeCompare(b.name)).map((s) =>
    `${s.name} namespaces="git" ${s.key.trim()}`
  );
  const extra = local.split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("#"));
  return [
    "# GENERATED by archon from the fleet's signers.ts (spec 047); emergency keys from",
    `# ${ALLOWED_SIGNERS_LOCAL}. Never edited by hand.`,
    ...lines,
    ...extra,
  ].join("\n") + "\n";
}

export interface TipCheck {
  ok: boolean;
  /** Why not, as a word (telemetry: archon.update.outcome = refused-<code>). */
  code?: "rollback" | "no-signers" | "unsigned" | "untrusted";
  /** Who signed it (the principal), when it is good. */
  signer?: string;
  reason?: string;
}

/**
 * May this host move from `current` to `tip`? The tip must descend from the
 * commit applied now (no rollback) and carry a good signature by a key in
 * `allowedFile` (the list this host already trusts).
 */
export async function checkTip(
  repo: string,
  tip: string,
  current: string,
  allowedFile = ALLOWED_SIGNERS,
  asUser?: string,
): Promise<TipCheck> {
  const git = (args: string[]) => run(["git", "-C", repo, ...args], { asUser });
  if (current && current !== tip) {
    const ff = await git(["merge-base", "--is-ancestor", current, tip]);
    if (!ff.ok) {
      return {
        ok: false,
        code: "rollback",
        reason: `${tip.slice(0, 10)} does not come after ${
          current.slice(0, 10)
        }, the commit this host applied (a rollback or a rewritten history)`,
      };
    }
  }
  const allowed = (await readTextOr(allowedFile)) ?? "";
  if (!allowed.split("\n").some((l) => l.trim() && !l.startsWith("#"))) {
    return {
      ok: false,
      code: "no-signers",
      reason: `${allowedFile} lists no signer: nothing can be approved`,
    };
  }
  const v = await git([
    "-c",
    "gpg.format=ssh",
    "-c",
    "gpg.ssh.program=ssh-keygen",
    "-c",
    `gpg.ssh.allowedSignersFile=${allowedFile}`,
    "verify-commit",
    "--raw",
    tip,
  ]);
  const out = v.stderr + v.stdout;
  const who = out.match(/Good "git" signature for (\S+) with/)?.[1];
  if (v.ok && who) return { ok: true, signer: who };
  const unsigned = /no signature|not signed|missing signature/i.test(out) || !out.trim();
  return {
    ok: false,
    code: unsigned ? "unsigned" : "untrusted",
    reason: unsigned
      ? `${tip.slice(0, 10)} is not signed: approve it with a signed commit (git commit -S)`
      : `${tip.slice(0, 10)} is not signed by a key this host trusts`,
  };
}

/** Whether this machine checks approvals (a host installed by Archon has the file). */
export function enforcing(): Promise<boolean> {
  return exists(ALLOWED_SIGNERS);
}

/** The signing setup of the person running a command on the boot machine or a workstation. */
export async function signingSetup(): Promise<Array<{ ok: boolean; what: string; fix?: string }>> {
  const cfg = async (k: string) => (await run(["git", "config", "--get", k])).stdout.trim();
  const out: Array<{ ok: boolean; what: string; fix?: string }> = [];
  const fmt = await cfg("gpg.format");
  const key = await cfg("user.signingkey");
  const sign = await cfg("commit.gpgsign");
  out.push({
    ok: fmt === "ssh" && !!key && sign === "true",
    what: `git signs commits with SSH (gpg.format=${fmt || "unset"}, commit.gpgsign=${
      sign || "unset"
    })`,
    fix:
      "git config --global gpg.format ssh; git config --global user.signingkey <key file>; git config --global commit.gpgsign true",
  });
  if (key && !key.startsWith("key::") && await exists(key.replace(/\.pub$/, ""))) {
    const priv = key.replace(/\.pub$/, "");
    // An encrypted key cannot be read with an empty passphrase.
    const plain = await run(["ssh-keygen", "-y", "-P", "", "-f", priv]);
    out.push({
      ok: !plain.ok,
      what: `the signing key ${priv} is ${plain.ok ? "NOT" : ""} protected by a passphrase`.replace(
        "  ",
        " ",
      ),
      fix: `ssh-keygen -p -f ${priv} (set a passphrase you type, never store)`,
    });
    const pub = (await readTextOr(priv + ".pub"))?.trim().split(" ").slice(0, 2).join(" ");
    const agent = await run(["ssh-add", "-L"]);
    const loaded = !!pub && agent.ok && agent.stdout.includes(pub);
    out.push({
      ok: !loaded,
      what: loaded
        ? "the signing key is loaded in an ssh-agent: anything running as you can sign"
        : "the signing key is not in an ssh-agent (each signature asks for the passphrase)",
      fix: "ssh-add -d " + priv,
    });
  }
  return out;
}
