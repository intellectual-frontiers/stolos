/**
 * `bun run gen` and `bun run check:ontology` (spec 101-ladder FR-001, FR-004, FR-005): the generator of Stolos' ontology
 * (`ontology/stolos/`, rung 0). From the ontology's typed values it writes:
 *
 * - `ontology/stolos.auto.ttl`, the ontology as canonical Turtle (commons 0012-ontology FR-006), for RDF tools and for a person reviewing
 *   a change of meaning;
 * - `src/archon/ontology.auto.ts`, each code list's keys as a union type and an array, which the code imports instead of writing the
 *   words again;
 * - the ladder's table of the constitution (between `<!-- ladder:begin -->` and `<!-- ladder:end -->`) and the layout of `AGENTS.md`
 *   (between `<!-- layout:begin -->` and `<!-- layout:end -->`), from the rungs of `ontology/stolos/architecture.ts`.
 *
 * Before it writes anything it checks what a type cannot state (commons' `rdf.validate`) and that every `stolos:` term a specification
 * names is one the ontology defines (Article 0: a term is defined before a specification uses it); either stops it with exit 2.
 * `--check` writes nothing and exits 1 where a file is not what the ontology makes. `tools/gen-assets.ts` runs it first, so that
 * `bun run gen` and `bun run gen --check` cover it.
 *
 * ```sh
 * bun tools/ontology.ts            # write the generated files
 * bun tools/ontology.ts --check    # exit 1 where one is stale (bun run check:ontology)
 * ```
 *
 * @module
 */
// Spec: 101-ladder FR-001, FR-004, FR-005
import { rdf } from "@intellectual-frontiers/commons/ts/kernel";
import { fs, path, proc } from "@intellectual-frontiers/commons/ts/runtime";
import { CODE_LISTS, definedTerms, files, rungs, STOLOS } from "../ontology/stolos/mod.ts";

const ROOT = path.resolve(path.dirname(path.fromFileUrl(import.meta.url)), "..");
const RUN = "bun run gen";
const WIDTH = 100;

/** The canonical Turtle of the whole ontology. */
export function turtleText(): string {
  const prefixes = new Map(files.flatMap((f) => f.prefixes).map((p) => [p.prefix, p]));
  return rdf.turtle({
    comments: [
      `AUTO-GENERATED by tools/ontology.ts (${RUN}) from ${files.map((f) => f.module).join(", ")} (spec 101-ladder FR-005). Do not edit: change the ontology.`,
    ],
    prefixes: [...prefixes.values()],
    triples: rdf.triplesOf(files.flatMap((f) => f.individuals)),
  });
}

/** A declaration on one line where it fits the formatter's width, else one item a line, as `bun fmt` writes it. */
function fitted(
  head: string,
  items: readonly string[],
  open: string,
  close: string,
  sep: string,
  lead: string,
): string {
  const one = `${head}${open}${items.join(sep)}${close};`;
  if (one.length <= WIDTH) return `${one}\n`;
  if (lead === "|") {
    const next = `  ${items.join(sep)};`;
    if (next.length <= WIDTH) return `${head.trimEnd()}\n${next}\n`;
    return `${head.trimEnd()}\n${items.map((i) => `  | ${i}`).join("\n")};\n`;
  }
  return `${head}${open.trimEnd()}\n${items.map((i) => `  ${i},`).join("\n")}\n${close.trimStart()};\n`;
}

/** The code lists' unions and arrays, as `src/archon/ontology.auto.ts`. */
export function unionsText(): string {
  let out = `/**
 * GENERATED by \`${RUN}\` (tools/ontology.ts) from \`ontology/stolos/codes.ts\`; never edit by hand. Spec 101-ladder FR-005: each
 * code list of Stolos' ontology as the union of its keys, the type the engine branches on, and the array of them in the ontology's order.
 *
 * @module
 */
`;
  for (const [type, c] of Object.entries<CodeListEntry>(CODE_LISTS)) {
    const keys = Object.keys(c.list).map((k) => JSON.stringify(k));
    const cited = [
      ...new Set(Object.values<rdf.AnyIndividual>(c.list).flatMap((i) => specsOf(i))),
    ].join(", ");
    out += `\n/** ${c.what} (\`stolos:${c.class ?? type}\`; ${cited}). */\n`;
    out += fitted(`export type ${type} = `, keys, "", "", " | ", "|");
    out += `\n/** Every {@link ${type}}, in the ontology's order. */\n`;
    out += fitted(`export const ${c.array}: readonly ${type}[] = `, keys, "[", "]", ", ", ",");
    if (c.data) out += dataText(type, c, c.data);
  }
  return out;
}

/** A code list in `CODE_LISTS`: its generated array, and optionally the facts of each code written as typed data. */
type CodeListEntry = {
  readonly class?: string;
  readonly array: string;
  readonly list: Readonly<Record<string, rdf.AnyIndividual>>;
  readonly what: string;
  readonly data?: {
    readonly name: string;
    readonly doc: string;
    readonly fields: Readonly<Record<string, string>>;
    /** Text written after the record (a named constant read from it). */
    readonly after?: string;
  };
};

/** The facts of each code of a list (its `data` fields) as a typed record, for example the listeners' protocols and ports. */
function dataText(
  type: string,
  c: CodeListEntry,
  data: NonNullable<CodeListEntry["data"]>,
): string {
  const shape = Object.entries(data.fields)
    .map(([k, t]) => `${k}: ${t}`)
    .join("; ");
  const rows = Object.entries(c.list).map(([key, i]) => {
    const values = (i as unknown as { values: Record<string, unknown> }).values;
    const fields = Object.keys(data.fields).map((f) => {
      const v = values[f];
      // A reference to another code: the key of that code in its own list.
      if (typeof v === "object" && v !== null && "iri" in v)
        return `${f}: ${JSON.stringify(keyOfIri(String(v.iri)))}`;
      return `${f}: ${JSON.stringify(v)}`;
    });
    const name = /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
    return `  ${name}: { ${fields.join(", ")} },`;
  });
  return `\n/** ${data.doc}. */\nexport const ${data.name}: Record<${type}, { ${shape} }> = {\n${rows.join("\n")}\n};\n${data.after ? `\n${data.after}\n` : ""}`;
}

/** The key of a code (its notation) from its IRI (`...#listener-boot-http` is `boot-http`). */
function keyOfIri(iri: string): string {
  const local = iri.slice(STOLOS.iri.length);
  return local.slice(local.indexOf("-") + 1);
}

function specsOf(i: rdf.AnyIndividual): string[] {
  return i.statements
    .filter((s) => s.predicate.iri === `${STOLOS.iri}spec`)
    .flatMap((s) => s.objects.filter((o) => typeof o === "string"));
}

/** "nothing", "0", "0, 1", "0 to 2": the rungs a rung may rely on. */
export function reliesOn(numbers: readonly number[]): string {
  if (numbers.length === 0) return "nothing";
  const sorted = [...numbers].sort((a, b) => a - b);
  const first = sorted[0] ?? 0;
  const last = sorted[sorted.length - 1] ?? 0;
  if (sorted.length >= 3 && last - first === sorted.length - 1) return `${first} to ${last}`;
  return sorted.join(", ");
}

function rungFacts(): readonly {
  readonly n: number;
  readonly label: string;
  readonly purpose: string;
  readonly homes: string;
  readonly relies: string;
  readonly proved: string;
}[] {
  return rungs.map((r) => ({
    n: r.values.rungNumber,
    label: r.values.label.value,
    purpose: r.values.definition.value,
    homes: (r.values.home ?? []).map((h) => `\`${h}\``).join(", "),
    relies: reliesOn(
      (r.values.mayRelyOn ?? []).map(
        (m) => rungs.find((x) => x.iri === m.iri)?.values.rungNumber ?? -1,
      ),
    ),
    proved: (r.values.provedBy ?? []).map((p) => `\`${p}\``).join(", "),
  }));
}

/** The constitution's ladder table, between its markers. */
export function ladderTable(): string {
  const rows = rungFacts().map(
    (r) => `| ${r.n} ${r.label} | ${r.purpose} | ${r.homes} | ${r.relies} | ${r.proved} |`,
  );
  return [
    "<!-- ladder:begin -->",
    "| Rung | Purpose | Home | May rely on | Proved by |",
    "|---|---|---|---|---|",
    ...rows,
    "<!-- ladder:end -->",
  ].join("\n");
}

/** `AGENTS.md`'s layout, between its markers. */
export function layoutList(): string {
  const items = rungFacts().map(
    (r) => `- **${r.n} ${r.label}** (relies on ${r.relies}): ${r.homes}. ${r.purpose}`,
  );
  return ["<!-- layout:begin -->", "", ...items, "", "<!-- layout:end -->"].join("\n");
}

/** A file's text with the block between two markers replaced, or undefined where the markers are not there. */
export function between(
  text: string,
  block: string,
  begin: string,
  end: string,
): string | undefined {
  const a = text.indexOf(begin);
  const b = text.indexOf(end);
  if (a < 0 || b < a) return undefined;
  return text.slice(0, a) + block + text.slice(b + end.length);
}

/** Every `stolos:` term a specification (spec.md, plan.md, tasks.md) names that the ontology does not define, as `file: term`. */
export async function undefinedTerms(root = ROOT): Promise<readonly string[]> {
  const defined = definedTerms();
  const out: string[] = [];
  for (const spec of await fs.listDirs(path.join(root, "specs"))) {
    for (const name of ["spec.md", "plan.md", "tasks.md"]) {
      const text = await fs.readTextOr(path.join(root, "specs", spec, name));
      if (text === undefined) continue;
      for (const m of text.matchAll(/(?<![\w:/.-])stolos:([A-Za-z][A-Za-z0-9-]*)/g)) {
        const t = `stolos:${m[1] ?? ""}`;
        if (!defined.has(t)) out.push(`specs/${spec}/${name}: ${t}`);
      }
    }
  }
  return out;
}

/** What the ontology makes: each file's path from the root, and its text. */
export async function wanted(root = ROOT): Promise<ReadonlyMap<string, string> | string> {
  const want = new Map<string, string>([
    ["ontology/stolos.auto.ttl", turtleText()],
    ["src/archon/ontology.auto.ts", unionsText()],
  ]);
  const marked: readonly (readonly [string, string, string, string])[] = [
    [
      ".specify/memory/constitution.md",
      ladderTable(),
      "<!-- ladder:begin -->",
      "<!-- ladder:end -->",
    ],
    ["AGENTS.md", layoutList(), "<!-- layout:begin -->", "<!-- layout:end -->"],
  ];
  for (const [file, block, begin, end] of marked) {
    const text = await fs.readTextOr(path.join(root, file));
    const next = text === undefined ? undefined : between(text, block, begin, end);
    if (next === undefined) return `${file} has no block between ${begin} and ${end}`;
    want.set(file, next);
  }
  return want;
}

/** The generator: 0 written or fresh, 1 stale (with `check`), 2 the ontology broken. Prints what it did. */
export async function generate(check: boolean, root = ROOT): Promise<number> {
  const broken = rdf.validate(files.flatMap((f) => f.individuals)).map(rdf.formatRdfFinding);
  const unknown = (await undefinedTerms(root)).map(
    (u) => `${u} is not a term the ontology defines: define it in ontology/stolos/ first`,
  );
  const want = await wanted(root);
  const problems = [...broken, ...unknown, ...(typeof want === "string" ? [want] : [])];
  if (problems.length > 0 || typeof want === "string") {
    for (const p of problems) console.error(`ontology: ${p}`);
    return 2;
  }
  if (check) {
    const stale: string[] = [];
    for (const [rel, text] of want)
      if ((await fs.readTextOr(path.join(root, rel))) !== text) stale.push(rel);
    for (const s of stale)
      console.error(`ontology: ${s} is not what the ontology makes: run \`${RUN}\``);
    return stale.length > 0 ? 1 : 0;
  }
  for (const [rel, text] of want)
    if (await fs.writeIfChanged(path.join(root, rel), text)) console.log(`ontology: wrote ${rel}`);
  return 0;
}

if (import.meta.main) proc.exit(await generate(proc.args.includes("--check")));
