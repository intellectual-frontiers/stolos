/**
 * `bun run gen` (specs 046-engine-instance, 096-bun-runtime): the engine's own text files (the
 * constitution, each specification, the guides (each module's `@module` JSDoc, as
 * `docs/<name>.md`: see `src/archon/core/guides.ts`), the base dotfile layer under `home/`, the
 * prompt theme, the bootstrap scripts under `bin/`, the vendored Datastar) as one generated module,
 * `src/archon/assets.auto.ts`, so that they travel inside the package and are read the same way
 * from a checkout and from `node_modules`. `bun run gen --check` fails when it is stale.
 *
 * Spec 096: the package is installed whole and `bun.lock` holds the integrity of its tarball, so
 * there is no longer a `modules.auto.ts` naming every module for a lockfile to pin.
 *
 * @module
 */
import { lf } from "@intellectual-frontiers/commons/ts/kernel";
import { fs, path, proc } from "@intellectual-frontiers/commons/ts/runtime";
import { guideMarkdown, GUIDES } from "../src/archon/core/guides.ts";

const ROOT = path.resolve(path.dirname(path.fromFileUrl(import.meta.url)), "..");
const OUT = path.join(ROOT, "src/archon/assets.auto.ts");

/** The files under a folder of the repository, as repository paths with `/`. */
async function under(dir: string): Promise<string[]> {
  return (await fs.walkFiles(path.join(ROOT, dir))).map((f) => `${dir}/${f.replaceAll("\\", "/")}`);
}

const files = [
  ".specify/memory/constitution.md",
  "src/archon/shell/archon.omp.json",
  ...(await under("specs")).filter((f) => f.endsWith("/spec.md")),
  ...(await under("home")),
  // Spec 062: the bootstrap scripts' template (fleets get their copy from it).
  "bin/bootstrap.sh",
  "bin/bootstrap.windows.ps1",
  "bin/stolos-probe.sh",
  "bin/stolos-probe.ps1",
  "bin/integrate.sh",
  "bin/integrate.windows.ps1",
  // Spec 065: Datastar, vendored and served by the consoles from the server itself.
  "vendor/datastar/datastar-1.0.4.js",
].sort();

const entries: Array<readonly [string, string]> = [];
for (const f of files) entries.push([f, lf(await fs.readTextFile(path.join(ROOT, f)))]);
// The guides: extracted from the modules whose documentation they are (one source).
for (const g of GUIDES) {
  entries.push([
    `docs/${g.name}.md`,
    guideMarkdown(lf(await fs.readTextFile(path.join(ROOT, g.module)))),
  ]);
}
entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const text = `/**
 * GENERATED by \`bun run gen\` (tools/gen-assets.ts); never edit by hand. Spec
 * 046-engine-instance: the engine's text files, carried as a module.
 *
 * @module
 */

/** The engine's text files by repository path. */
export const ASSETS: Readonly<Record<string, string>> = {
${entries.map(([f, t]) => `  ${JSON.stringify(f)}: ${JSON.stringify(t)},\n`).join("")}};
`;

if (proc.args.includes("--check")) {
  const have = await fs.readTextOr(OUT, "");
  if (have !== text) {
    console.error(`${path.relative(ROOT, OUT)} is stale: run \`bun run gen\``);
    proc.exit(1);
  }
} else {
  await fs.writeTextFile(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${entries.length} files)`);
}
