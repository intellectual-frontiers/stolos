// Spec 046-engine-instance: the engine's own text files (the constitution,
// each specification, the guides (each module's @module JSDoc, as docs/<name>.md: see
// src/archon/core/guides.ts), the base dotfile layer under
// home/, the prompt theme, the bootstrap scripts under bin/) as one generated TypeScript module, so that an
// engine imported from GitHub (`@stolos/`) carries them: only modules travel
// with an import. `deno task gen` writes src/archon/assets.auto.ts;
// `deno task gen --check` fails when it is stale.

import { join, relative } from "../src/archon/core/path.ts";
import { guideMarkdown, GUIDES } from "../src/archon/core/guides.ts";

const ROOT = new URL("..", import.meta.url).pathname.replace(/\/$/, "");
const OUT = join(ROOT, "src/archon/assets.auto.ts");

function walk(dir: string): string[] {
  const out: string[] = [];
  let entries: Deno.DirEntry[];
  try {
    entries = [...Deno.readDirSync(dir)];
  } catch {
    return out;
  }
  for (const e of entries) {
    const p = join(dir, e.name);
    if (e.isDirectory) out.push(...walk(p));
    else if (e.isFile) out.push(p);
  }
  return out;
}

const files = [
  join(ROOT, ".specify/memory/constitution.md"),
  join(ROOT, "src/archon/shell/archon.omp.json"),
  ...walk(join(ROOT, "specs")).filter((f) => f.endsWith("/spec.md")),
  ...walk(join(ROOT, "home")),
  // Spec 062: the bootstrap scripts' template (fleets get their copy from it).
  join(ROOT, "bin/bootstrap.sh"),
  join(ROOT, "bin/bootstrap.windows.ps1"),
  join(ROOT, "bin/stolos-probe.sh"),
  join(ROOT, "bin/stolos-probe.ps1"),
  join(ROOT, "bin/integrate.sh"),
  join(ROOT, "bin/integrate.windows.ps1"),
  // Spec 065: Datastar, vendored and served by the consoles from the server itself.
  join(ROOT, "vendor/datastar/datastar-1.0.4.js"),
].map((f) => relative(ROOT, f).replaceAll("\\", "/")).sort();

// The guides: extracted from the modules whose documentation they are (one source).
const guides: Array<[string, string]> = GUIDES.map((g) => [
  `docs/${g.name}.md`,
  guideMarkdown(Deno.readTextFileSync(join(ROOT, g.module))),
]);
let body = "";
for (
  const [f, t] of [
    ...files.map((f): [string, string] => [f, Deno.readTextFileSync(join(ROOT, f))]),
    ...guides,
  ]
    .sort(([a], [b]) => a.localeCompare(b))
) {
  body += `  ${JSON.stringify(f)}: ${JSON.stringify(t)},\n`;
}
const text = `// GENERATED by \`deno task gen\` (tools/gen-assets.ts); never edit by hand.
// Spec 046-engine-instance: the engine's text files, carried as a module.

export const ASSETS: Readonly<Record<string, string>> = {
${body}};
`;

// Spec 046: every engine module, named statically, so that a fleet's deno.lock
// (through its engine.ts) pins all of them, including those imported on demand;
// the launcher runs with --frozen. Never executed, only cached.
const MODULES = join(ROOT, "src/archon/modules.auto.ts");
const modules = walk(join(ROOT, "src"))
  .filter((f) => f.endsWith(".ts") && !f.endsWith(".auto.ts"))
  .map((f) => relative(join(ROOT, "src/archon"), f).replaceAll("\\", "/"))
  .map((f) => (f.startsWith(".") ? f : `./${f}`))
  .sort();
const modulesText = `// GENERATED by \`deno task gen\` (tools/gen-assets.ts); never edit by hand.
// Spec 046-engine-instance: every engine module, so that a fleet's deno.lock pins
// them all (a fleet's engine.ts imports this file; nothing runs it).
${modules.map((m) => `import "${m}";`).join("\n")}
import "./assets.auto.ts";
`;

const outputs: Array<[string, string]> = [[OUT, text], [MODULES, modulesText]];
if (Deno.args.includes("--check")) {
  for (const [file, want] of outputs) {
    const have = await Deno.readTextFile(file).catch(() => "");
    if (have !== want) {
      console.error(`${relative(ROOT, file)} is stale: run \`deno task gen\``);
      Deno.exit(1);
    }
  }
} else {
  for (const [file, want] of outputs) await Deno.writeTextFile(file, want);
  console.log(
    `wrote ${relative(ROOT, OUT)} (${files.length} files) and ${
      relative(ROOT, MODULES)
    } (${modules.length} modules)`,
  );
}
